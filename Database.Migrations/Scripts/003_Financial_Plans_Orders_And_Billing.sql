-- 2. Tabela: Orders (Transações e Pedidos do Checkout Transparente Mercado Pago - PIX e Cartão)
CREATE TABLE IF NOT EXISTS dbo.Orders (
    Id UUID NOT NULL DEFAULT gen_random_uuid(),
    TenantId UUID NOT NULL,
    UserId UUID NULL,
    PlanId UUID NULL,
    TotalAmount NUMERIC(18,2) NOT NULL,
    TotalPaidAmount NUMERIC(18,2) NOT NULL DEFAULT 0.00,
    Currency VARCHAR(10) NOT NULL DEFAULT 'BRL',
    Status VARCHAR(50) NOT NULL DEFAULT 'pending',
    PaymentMethod VARCHAR(50) NOT NULL,
    MpPaymentId VARCHAR(100) NULL,
    ExternalReference VARCHAR(150) NULL,
    PayerEmail VARCHAR(255) NULL,
    PayerDocumentType VARCHAR(20) NULL,
    PayerDocumentNumber VARCHAR(30) NULL,
    PayerName VARCHAR(255) NULL,
    PayerZipCode VARCHAR(20) NULL,
    PayerStreetName VARCHAR(255) NULL,
    PayerStreetNumber VARCHAR(50) NULL,
    PayerComplement VARCHAR(150) NULL,
    PayerNeighborhood VARCHAR(150) NULL,
    PayerCity VARCHAR(150) NULL,
    PayerFederalUnit VARCHAR(10) NULL,
    PixQrCode TEXT NULL,
    PixQrCodeBase64 TEXT NULL,
    PixExpirationDate TIMESTAMPTZ NULL,
    TicketUrl TEXT NULL,
    CardLastFourDigits VARCHAR(10) NULL,
    CardBrand VARCHAR(50) NULL,
    Installments INT NOT NULL DEFAULT 1,
    PaidAt TIMESTAMPTZ NULL,
    CreatedAt TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UpdatedAt TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT PK_Orders PRIMARY KEY (Id),
    CONSTRAINT FK_Orders_Tenants FOREIGN KEY (TenantId) 
        REFERENCES dbo.Tenants(Id) ON DELETE CASCADE,
    CONSTRAINT FK_Orders_Users FOREIGN KEY (UserId) 
        REFERENCES dbo.Users(Id),
    CONSTRAINT FK_Orders_Plans FOREIGN KEY (PlanId) 
        REFERENCES dbo.Plans(Id)
);

CREATE INDEX IF NOT EXISTS IX_Orders_Tenant_CreatedAt
ON dbo.Orders (TenantId, CreatedAt DESC)
INCLUDE (TotalAmount, TotalPaidAmount, Status, PaymentMethod, MpPaymentId, PaidAt);

CREATE INDEX IF NOT EXISTS IX_Orders_ExternalReference 
ON dbo.Orders (ExternalReference);

-- 3. Tabela: OrderItems (Itens de Pedido)
CREATE TABLE IF NOT EXISTS dbo.OrderItems (
    Id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    OrderId UUID NOT NULL,
    Title VARCHAR(150) NOT NULL,
    UnitPrice NUMERIC(18,2) NOT NULL,
    Quantity INT NOT NULL DEFAULT 1,
    ExternalCode VARCHAR(100) NULL,
    CONSTRAINT PK_OrderItems PRIMARY KEY (Id),
    CONSTRAINT FK_OrderItems_Orders FOREIGN KEY (OrderId) 
        REFERENCES dbo.Orders(Id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS IX_OrderItems_OrderId 
ON dbo.OrderItems (OrderId);

-- 4. Tabela: TenantBillingProfiles (Dados Fiscais CPF/CNPJ e Endereço de Cobrança 1:1 por Tenant)
CREATE TABLE IF NOT EXISTS dbo.TenantBillingProfiles (
    Id UUID NOT NULL DEFAULT gen_random_uuid(),
    TenantId UUID NOT NULL,
    LegalName VARCHAR(255) NOT NULL,
    TradeName VARCHAR(255) NULL,
    DocumentType VARCHAR(10) NOT NULL DEFAULT 'CPF',
    DocumentNumber VARCHAR(30) NOT NULL,
    Email VARCHAR(255) NULL,
    Phone VARCHAR(50) NULL,
    ZipCode VARCHAR(20) NOT NULL,
    StreetName VARCHAR(255) NOT NULL,
    StreetNumber VARCHAR(50) NOT NULL,
    Complement VARCHAR(150) NULL,
    Neighborhood VARCHAR(150) NOT NULL,
    City VARCHAR(150) NOT NULL,
    FederalUnit VARCHAR(10) NOT NULL,
    CreatedAt TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UpdatedAt TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT PK_TenantBillingProfiles PRIMARY KEY (Id),
    CONSTRAINT FK_TenantBillingProfiles_Tenants FOREIGN KEY (TenantId)
        REFERENCES dbo.Tenants(Id) ON DELETE CASCADE,
    CONSTRAINT UQ_TenantBillingProfiles_TenantId UNIQUE (TenantId)
);

CREATE INDEX IF NOT EXISTS IX_TenantBillingProfiles_TenantId_Covering
ON dbo.TenantBillingProfiles (TenantId)
INCLUDE (LegalName, DocumentType, DocumentNumber, ZipCode, StreetName, StreetNumber, Neighborhood, City, FederalUnit, Email, Phone);
